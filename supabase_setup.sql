-- Zotero Lab UPTC: tabla mínima para puntuaciones compartidas.
-- Ejecutar en Supabase > SQL Editor.
-- No almacena contraseñas ni datos sensibles. Los alias y puntuaciones serán públicos
-- para quienes tengan acceso al proyecto y conozcan el código del aula.
create table if not exists public.zotero_lab_scores (
  id bigint generated by default as identity primary key,
  room_code text not null check (char_length(room_code) between 1 and 30),
  student_name text not null check (char_length(student_name) between 1 and 40),
  score integer not null check (score between 0 and 100),
  correct_answers integer not null check (correct_answers between 0 and 5),
  total_questions integer not null default 5 check (total_questions = 5),
  created_at timestamptz not null default now()
);

alter table public.zotero_lab_scores enable row level security;

-- Retirar políticas previas con estos nombres para poder volver a ejecutar este archivo.
drop policy if exists "scores_read_for_classroom" on public.zotero_lab_scores;
drop policy if exists "scores_insert_for_classroom" on public.zotero_lab_scores;

-- Permite leer el ranking y enviar resultados, pero no editar ni borrar registros desde el navegador.
-- IMPORTANTE: esta configuración es adecuada para una demostración abierta, no para calificaciones oficiales.
create policy "scores_read_for_classroom"
on public.zotero_lab_scores for select
to anon, authenticated
using (true);

create policy "scores_insert_for_classroom"
on public.zotero_lab_scores for insert
to anon, authenticated
with check (
  char_length(room_code) between 1 and 30
  and char_length(student_name) between 1 and 40
  and score between 0 and 100
  and correct_answers between 0 and 5
  and total_questions = 5
);

grant select, insert on public.zotero_lab_scores to anon, authenticated;
grant usage, select on sequence public.zotero_lab_scores_id_seq to anon, authenticated;
